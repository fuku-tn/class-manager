-- Trạng thái đăng ký từ Google Sheet (STATUS: Đã thanh toán / Đã cọc / Chưa thanh toán / Scholarship / ...), bảng Potential,
-- và 2 loại sự kiện mới. KHÔNG có số tiền. Chạy trên Supabase; an toàn chạy lại.
alter table enrollments add column if not exists sheet_status text;

alter table enrollment_events drop constraint if exists enrollment_events_event_check;
alter table enrollment_events add constraint enrollment_events_event_check
  check (event in ('enrolled','status_changed','removed','missing_from_sheet','reappeared','graduation','sheet_status','moved_to_potential'));

create table if not exists potential_students (
  id           bigint generated by default as identity primary key,
  class_id     bigint not null references classes(id) on delete cascade,
  student_id   bigint not null references students(id) on delete cascade,
  class_code   text,
  student_code text,
  full_name    text,
  last_status  text,
  reason       text not null check (reason in ('unpaid','removed_from_sheet')),
  snapshot     jsonb,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (class_id, student_id)
);
alter table potential_students enable row level security;
create index if not exists idx_potential_class on potential_students (class_id);

