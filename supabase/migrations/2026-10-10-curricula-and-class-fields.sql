create table if not exists curricula (
  id            bigint generated by default as identity primary key,
  code          text not null unique,            -- vd BIE-8, BIE-12, BIH-20, BIH-11
  program       text not null,                   -- BIE, BIH...
  name          text not null,
  session_count integer not null,
  total_hours   numeric(6,1) not null default 0
);

create table if not exists curriculum_items (
  id            bigint generated by default as identity primary key,
  curriculum_id bigint not null references curricula(id) on delete cascade,
  session_no    integer not null,
  seq           integer not null,                -- thứ tự dòng trong buổi
  phase         text,
  module        text,
  tools         text,
  hours         numeric(4,1),
  content       text,
  unique (curriculum_id, session_no, seq)
);

alter table classes add column if not exists short_code      text;                     -- BIE101
alter table classes add column if not exists program         text;                     -- BIE
alter table classes add column if not exists delivery_mode   text check (delivery_mode in ('Online','Offline','Hybrid'));
alter table classes add column if not exists shift           text check (shift in ('morning','afternoon','evening','full_day'));
alter table classes add column if not exists end_date        date;
alter table classes add column if not exists next_short_code text;                     -- khóa kế tiếp
alter table classes add column if not exists curriculum_id   bigint references curricula(id) on delete set null;
create unique index if not exists classes_short_code_key on classes (short_code) where short_code is not null;

alter table students    add column if not exists gender text check (gender in ('Female','Male'));
alter table enrollments add column if not exists registration_source text;
alter table enrollments add column if not exists carried_over boolean not null default false; -- học bằng suất chuyển từ khóa trước

alter table curricula        enable row level security;
alter table curriculum_items enable row level security;
