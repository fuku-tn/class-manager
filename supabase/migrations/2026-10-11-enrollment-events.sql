-- Nhật ký sự kiện ghi danh (thêm vào lớp, đổi trạng thái, gỡ khỏi lớp, không còn thấy trong Google Sheet).
-- Chạy trên Supabase SQL Editor; an toàn chạy lại.
alter table enrollments add column if not exists origin text not null default 'web';
alter table enrollments drop constraint if exists enrollments_origin_check;
alter table enrollments add constraint enrollments_origin_check check (origin in ('web','sheet','import'));
-- Ghi danh đã có: coi là 'import' (trung tính). Lần đồng bộ Google Sheet kế tiếp đặt 'sheet' cho đúng những ghi danh
-- có trong Sheet; chỉ ghi danh 'sheet' mới bị dò "không còn thấy trong Sheet".
update enrollments set origin = 'import' where origin = 'web' and (customer_id is not null or registration_source is not null);

create table if not exists enrollment_events (
  id            bigint generated by default as identity primary key,
  enrollment_id bigint,
  class_id      bigint,
  class_code    text,
  student_id    bigint,
  student_code  text,
  full_name     text,
  event         text not null check (event in ('enrolled','status_changed','removed','missing_from_sheet','reappeared')),
  from_status   text,
  to_status     text,
  source        text not null check (source in ('web','sync','import')),
  actor_id      bigint references users(id) on delete set null,
  actor_name    text,
  note          text,
  created_at    timestamptz not null default now()
);
create index if not exists idx_enrollment_events_class on enrollment_events (class_id, id desc);
create index if not exists idx_enrollment_events_enrollment on enrollment_events (enrollment_id, id desc);
alter table enrollment_events enable row level security;
