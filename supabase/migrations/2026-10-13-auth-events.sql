-- Nhật ký đăng nhập / đổi mật khẩu (cũng dùng để khóa tạm khi đăng nhập sai nhiều lần). Chạy trên Supabase; an toàn chạy lại.
create table if not exists auth_events (
  id         bigint generated by default as identity primary key,
  at         timestamptz not null default now(),
  event      text not null check (event in ('login_ok','login_fail','locked','password_changed','password_fail')),
  email      text,
  user_id    bigint,
  ip         text,
  user_agent text
);
alter table auth_events enable row level security;
create index if not exists idx_auth_events_key on auth_events (email, ip, at desc);
create index if not exists idx_auth_events_ip on auth_events (ip, at desc);

