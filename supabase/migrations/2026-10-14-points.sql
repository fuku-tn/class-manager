-- Điểm bài tập (HW) đồng bộ từ tab "Point" của Google Sheet. Chạy trên Supabase; an toàn chạy lại.
create table if not exists homework_scores (
  id            bigint generated by default as identity primary key,
  enrollment_id bigint not null references enrollments(id) on delete cascade,
  assignment_id bigint not null references assignments(id) on delete cascade,
  score         numeric(5,2) not null check (score >= 0 and score <= 10),
  module        text,
  updated_at    timestamptz not null default now(),
  unique (enrollment_id, assignment_id)
);
alter table homework_scores enable row level security;
create index if not exists idx_homework_scores_assignment on homework_scores (assignment_id);
