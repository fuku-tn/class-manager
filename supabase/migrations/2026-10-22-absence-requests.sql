-- Chỉ lưu: học viên, NGÀY nghỉ, mã thư (để truy vết), giờ nhận, trạng thái. KHÔNG lưu email người gửi, tiêu đề, nội dung thư.
create table if not exists absence_requests (
  id           bigint generated by default as identity primary key,
  student_id   bigint not null references students(id) on delete cascade,
  absence_date date not null,
  message_key  text,
  received_at  timestamptz,
  status       text not null default 'pending' check (status in ('pending','confirmed','dismissed')),
  reviewed_by  bigint references users(id) on delete set null,
  reviewed_at  timestamptz,
  created_at   timestamptz not null default now(),
  unique (student_id, absence_date)
);
alter table absence_requests enable row level security;
create index if not exists idx_absence_requests_date on absence_requests (absence_date);
