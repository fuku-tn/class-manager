-- Lịch giảng dạy từ bảng "Calendar" trên Google Sheet (Ngày, Buổi, Khóa, Nội dung, Số buổi, Hình thức, Loại, Ghi chú).
-- Bảng là bản chuẩn của Sheet: mỗi lượt đồng bộ thay toàn bộ nội dung. Chạy trên Supabase TRƯỚC khi đẩy code; an toàn chạy lại.
create table if not exists teaching_schedule (
  id           bigint generated by default as identity primary key,
  class_id     bigint references classes(id) on delete cascade,   -- null nếu mã lớp chưa có trong app (chỉ admin thấy)
  short_code   text not null,                                      -- BIH098
  session_date date not null,
  shift        text check (shift in ('morning','afternoon','evening','full_day')),
  session_no   integer,
  content      text,
  mode         text,                                               -- Offline / Online / Hybrid
  segment      text,                                               -- B2C / B2B
  note         text,                                               -- vd Khai giảng, Bế giảng
  instructor   text,                                               -- cột "Giảng viên" (tùy chọn, chưa có trong Sheet)
  updated_at   timestamptz not null default now()
);
alter table teaching_schedule enable row level security;
create index if not exists idx_teaching_schedule_date on teaching_schedule (session_date);
create index if not exists idx_teaching_schedule_class on teaching_schedule (class_id);
