-- Khảo sát sau khóa (đã loại họ tên/email/SĐT, câu trả lời chữ tự do và câu hỏi học phí). Chạy trên Supabase; an toàn chạy lại.
create table if not exists course_feedback (
  id           bigint generated by default as identity primary key,
  source_key   text not null unique,
  class_id     bigint references classes(id) on delete set null,
  short_code   text,
  submitted_at timestamptz,
  scores       jsonb not null default '{}'::jsonb,
  more_courses text check (more_courses in ('yes','maybe')),
  next_courses jsonb not null default '[]'::jsonb,
  created_at   timestamptz not null default now()
);
create index if not exists idx_course_feedback_class on course_feedback (class_id);

alter table course_feedback enable row level security;
