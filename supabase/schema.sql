-- Schema Postgres/Supabase tương ứng src/schema.sql (SQLite).
-- Dán toàn bộ file này vào Supabase → SQL Editor → Run. An toàn chạy lại (IF NOT EXISTS).

create table if not exists users (
  id            bigint generated by default as identity primary key,
  email         text not null unique,
  name          text not null,
  password_hash text not null,
  role          text not null default 'instructor' check (role in ('admin','instructor','guest')),
  active        boolean not null default true,
  created_at    timestamptz not null default now()
);

create table if not exists auth_sessions (
  token_hash text primary key,
  user_id    bigint not null references users(id) on delete cascade,
  expires_at timestamptz not null
);

create table if not exists enrollment_events (
  id            bigint generated by default as identity primary key,
  enrollment_id bigint,
  class_id      bigint,
  class_code    text,
  student_id    bigint,
  student_code  text,
  full_name     text,
  event         text not null check (event in ('enrolled','status_changed','removed','missing_from_sheet','reappeared')),
  from_status   text,
  to_status     text,
  source        text not null check (source in ('web','sync','import')),
  actor_id      bigint references users(id) on delete set null,
  actor_name    text,
  note          text,
  created_at    timestamptz not null default now()
);
create index if not exists idx_enrollment_events_class on enrollment_events (class_id, id desc);
create index if not exists idx_enrollment_events_enrollment on enrollment_events (enrollment_id, id desc);

create table if not exists sync_runs (
  id         bigint generated by default as identity primary key,
  source     text not null,
  ok         boolean not null,
  summary    jsonb,
  error      text,
  created_at timestamptz not null default now()
);

create table if not exists curricula (
  id            bigint generated by default as identity primary key,
  code          text not null unique,
  program       text not null,
  name          text not null,
  session_count integer not null,
  total_hours   numeric(6,1) not null default 0
);

create table if not exists curriculum_items (
  id            bigint generated by default as identity primary key,
  curriculum_id bigint not null references curricula(id) on delete cascade,
  session_no    integer not null,
  seq           integer not null,
  phase         text,
  module        text,
  tools         text,
  hours         numeric(4,1),
  content       text,
  unique (curriculum_id, session_no, seq)
);

create table if not exists classes (
  id         bigint generated by default as identity primary key,
  code       text not null unique,
  name       text not null,
  phase      text,
  start_date date,
  status     text not null default 'active' check (status in ('active','finished','archived')),
  short_code      text,
  program         text,
  delivery_mode   text check (delivery_mode in ('Online','Offline','Hybrid')),
  shift           text check (shift in ('morning','afternoon','evening','full_day')),
  end_date        date,
  next_short_code text,
  curriculum_id   bigint references curricula(id) on delete set null,
  created_at timestamptz not null default now()
);
create unique index if not exists classes_short_code_key on classes (short_code) where short_code is not null;

create table if not exists class_instructors (
  class_id bigint not null references classes(id) on delete cascade,
  user_id  bigint not null references users(id) on delete cascade,
  primary key (class_id, user_id)
);

create table if not exists students (
  id           bigint generated by default as identity primary key,
  student_code text not null unique,
  full_name    text not null,
  email        text,
  phone        text,
  gender       text check (gender in ('Female','Male')),
  created_at   timestamptz not null default now()
);

create table if not exists enrollments (
  id                 bigint generated by default as identity primary key,
  class_id           bigint not null references classes(id) on delete cascade,
  student_id         bigint not null references students(id) on delete cascade,
  customer_id        text,
  mode               text check (mode in ('Online','Offline','Hybrid')),
  course_status      text not null default 'active' check (course_status in ('active','deferred','dropped','completed')),
  certificate_status text,
  form               text,
  note               text,
  registration_source text,
  carried_over       boolean not null default false,
  origin             text not null default 'web' check (origin in ('web','sheet','import')),
  segment            text not null default 'b2c' check (segment in ('b2c','b2b')),
  company_name       text,
  created_at         timestamptz not null default now(),
  unique (class_id, student_id)
);

create table if not exists registration_forms (
  id                bigint generated by default as identity primary key,
  enrollment_id     bigint unique references enrollments(id) on delete cascade,
  short_code        text,
  submitted_at      timestamptz,
  delivery          text,
  department        text,
  job_title         text,
  hr_function       text,
  industry          text,
  province          text,
  experience        text,
  sources           jsonb not null default '[]'::jsonb,
  material_delivery text,
  goals             jsonb not null default '[]'::jsonb,
  email_hash        text,
  phone_hash        text,
  updated_at        timestamptz not null default now()
);
create index if not exists idx_registration_forms_pending on registration_forms (short_code) where enrollment_id is null;

create table if not exists sessions (
  id           bigint generated by default as identity primary key,
  class_id     bigint not null references classes(id) on delete cascade,
  session_no   integer not null,
  title        text,
  session_date date,
  held         boolean not null default false,
  unique (class_id, session_no)
);

create table if not exists attendance (
  id            bigint generated by default as identity primary key,
  enrollment_id bigint not null references enrollments(id) on delete cascade,
  session_id    bigint not null references sessions(id) on delete cascade,
  status        text not null check (status in ('present','late','absent','excused')),
  note          text,
  updated_at    timestamptz not null default now(),
  updated_by    bigint references users(id) on delete set null,
  unique (enrollment_id, session_id)
);

create table if not exists assignments (
  id        bigint generated by default as identity primary key,
  class_id  bigint not null references classes(id) on delete cascade,
  kind      text not null default 'hw' check (kind in ('hw','capstone')),
  seq       integer not null,
  title     text not null,
  due_date  date,
  collected boolean not null default false,
  unique (class_id, kind, seq)
);

create table if not exists submissions (
  id            bigint generated by default as identity primary key,
  enrollment_id bigint not null references enrollments(id) on delete cascade,
  assignment_id bigint not null references assignments(id) on delete cascade,
  status        text not null check (status in ('submitted','resubmit','missing')),
  challenge     boolean not null default false,
  note          text,
  updated_at    timestamptz not null default now(),
  updated_by    bigint references users(id) on delete set null,
  unique (enrollment_id, assignment_id)
);

create index if not exists idx_enrollments_class on enrollments(class_id);
create index if not exists idx_enrollments_student on enrollments (student_id);
create index if not exists idx_class_instructors_user on class_instructors (user_id);
create index if not exists idx_auth_sessions_user on auth_sessions (user_id);
create index if not exists idx_classes_curriculum on classes (curriculum_id);
create index if not exists idx_attendance_session on attendance(session_id);
create index if not exists idx_submissions_assignment on submissions(assignment_id);

-- BẢO MẬT: bật RLS cho mọi bảng và KHÔNG tạo policy nào.
-- Supabase tự mở "Data API" cho anon key; bảng có dữ liệu học viên (email, SĐT) mà không bật RLS
-- thì ai có anon key cũng đọc được. Server Node kết nối bằng chuỗi Postgres (vai trò postgres)
-- nên không bị RLS chặn. Khi sau này cho trình duyệt gọi thẳng Supabase, mới thêm policy theo lớp.
alter table users             enable row level security;
alter table auth_sessions     enable row level security;
alter table curricula         enable row level security;
alter table curriculum_items  enable row level security;
alter table classes           enable row level security;
alter table class_instructors enable row level security;
alter table students          enable row level security;
alter table enrollments       enable row level security;
alter table sessions          enable row level security;
alter table attendance        enable row level security;
alter table assignments       enable row level security;
alter table submissions       enable row level security;
alter table sync_runs         enable row level security;
alter table enrollment_events enable row level security;
alter table registration_forms enable row level security;
